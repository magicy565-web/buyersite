export function deriveEditorialSeatToken(secret,seatId){
  if(typeof secret!=='string'||secret.length<40||secret.length>512||
     !/^[a-z][a-z0-9-]{1,63}$/.test(seatId||''))fail('EDITORIAL_SECRET_INVALID',500);
  return createHmac('sha256',secret).update('buyersite-editorial-seat/v1\n'+seatId).digest('hex');
}

function authorizedSeat(request,secret,seatId){
  const header=request.headers.authorization;
  if(typeof header!=='string'||!header.startsWith('Bearer '))fail('MCP_UNAUTHORIZED',401);
  const given=Buffer.from(header.slice(7));
  const expected=Buffer.from(deriveEditorialSeatToken(secret,seatId));
  if(given.length!==expected.length||!timingSafeEqual(given,expected))fail('MCP_UNAUTHORIZED',401);
}

function toolList(seatId){
  const roleTools=specialized[seatId]||[];
  return [...common,...roleTools];
}

function jsonRpcError(id,code,message){
  return {jsonrpc:'2.0',id,error:{code,message}};
}
function toolResult(id,value){
  return {jsonrpc:'2.0',id,result:{
    content:[{type:'text',text:JSON.stringify(value)}],
    structuredContent:value,
    isError:false,
  }};
}
function toolFailure(id,error){
  const value={code:error.code||'EDITORIAL_TOOL_FAILED',message:safeError(error)};
  return {jsonrpc:'2.0',id,result:{
    content:[{type:'text',text:JSON.stringify(value)}],
    structuredContent:value,
    isError:true,
  }};
}
function safeError(error){
  return String(error?.code||error?.message||'Editorial tool failed').slice(0,300);
}

async function readRequestBody(request,maxBytes=400_000){
  const chunks=[];let size=0;
  for await(const chunk of request){
    size+=chunk.length;
    if(size>maxBytes)fail('MCP_REQUEST_TOO_LARGE',413);
    chunks.push(chunk);
  }
  const bytes=Buffer.concat(chunks);
  try{return JSON.parse(bytes.toString('utf8'));}
  catch{fail('MCP_JSON_INVALID',400);}
}

async function writeResponse(response,status,payload){
  response.statusCode=status;
  response.setHeader('content-type','application/json; charset=utf-8');
  response.setHeader('cache-control','no-store');
  response.setHeader('x-content-type-options','nosniff');
  response.end(payload===null?'':JSON.stringify(payload));
}

function requireArgs(args,allowed,required){
  if(!obj(args)||noExtra(args,allowed)||required.some(key=>args[key]===undefined))fail('MCP_ARGUMENTS_INVALID',400);
}

export function createEditorialMcpHandler({
  runtime,dispatcher,missionSecret,buildJob,projectRoot,
  capture=captureCompanyHomepage,
  clock=()=>new Date().toISOString(),
}={}){
  if(!runtime||typeof runtime.claimTask!=='function'||typeof missionSecret!=='string'||
     typeof buildJob!=='function')fail('EDITORIAL_MCP_DEPENDENCIES_REQUIRED',500);
  let background=Promise.resolve();

  const scheduleBackground=work=>{
    const result=background.then(work,work);
    background=result.catch(()=>undefined);
    return result;
  };
  const afterCompletion=async missionId=>{
    if(dispatcher?.dispatch) await dispatcher.dispatch(missionId).catch(()=>undefined);
  };
  const complete=async(seatId,args,artifact)=>{
    const result=await runtime.completeTask({...args,seatId,artifact});
    await afterCompletion(args.missionId);
    return result;
  };
  const claim=async(seatId,args)=>{
    requireArgs(args,['missionId','taskId','taskAccessToken'],['missionId','taskId','taskAccessToken']);
    return runtime.claimTask({...args,seatId});
  };

  async function callTool(seatId,name,args){
    switch(name){
      case 'buyersite_mission_get':
        requireArgs(args,['missionId','taskId','taskAccessToken'],['missionId','taskId','taskAccessToken']);
        return runtime.getTaskContext(args.missionId,args.taskId,seatId,args.taskAccessToken);
      case 'buyersite_task_claim':
        return claim(seatId,args);
      case 'buyersite_task_complete':
        requireArgs(args,['missionId','taskId','taskAccessToken','claimToken','artifact'],['missionId','taskId','taskAccessToken','claimToken','artifact']);
        return complete(seatId,args,args.artifact);
      case 'buyersite_task_fail':{
        requireArgs(args,['missionId','taskId','taskAccessToken','claimToken','code','message'],['missionId','taskId','taskAccessToken','claimToken','code','message']);
        const result=await runtime.failTask({...args,seatId});
        return result;
      }
      case 'buyersite_artifact_get':
        requireArgs(args,['missionId','artifactTaskId','currentTaskId','taskAccessToken'],['missionId','artifactTaskId','currentTaskId','taskAccessToken']);
        return runtime.getArtifact(args.missionId,args.artifactTaskId,seatId,args.currentTaskId,args.taskAccessToken);
      case 'buyersite_source_capture':{
        requireSeatTask(seatId,args,'research-editor','capture-source');
        const job=runtime.getJob(args.missionId);
        const page=await capture(job.input.url);
        const artifact={snapshot:page};
        return complete(seatId,args,artifact);
      }
      case 'buyersite_enterprise_compile':{
        requireSeatTask(seatId,args,'research-editor','compile-enterprise');
        const job=runtime.getJob(args.missionId);
        const sourceBytes=await runtime.readSourceBytes(args.missionId);
        const captureArtifact=await runtime.getArtifact(args.missionId,'capture-source',seatId,'compile-enterprise',args.taskAccessToken);
        const compiledResult=await compileStudioEdition(job,sourceBytes,{websiteSnapshot:captureArtifact.snapshot});
        const outline=planMagazineOutline(compiledResult.compiled);
        return complete(seatId,args,{
          compiled:compiledResult.compiled,
          outline,
          sourceBinding:compiledResult.sourceBinding,
        });
      }
      case 'buyersite_media_materialize':{
        requireSeatTask(seatId,args,'art-director','prepare-media');
        const work=async()=>{
          const job=runtime.getJob(args.missionId);
          const sourceBytes=await runtime.readSourceBytes(args.missionId);
          const snapshot=JSON.parse(sourceBytes.toString('utf8'));
          const compiledArtifact=await runtime.getArtifact(args.missionId,'compile-enterprise',seatId,'prepare-media',args.taskAccessToken);
          const artDirection=await runtime.getArtifact(args.missionId,'art-direction',seatId,'prepare-media',args.taskAccessToken);
          const compiled=compiledArtifact.compiled;
          const visualPlan={...compiled.visualPlan,art_direction:artDirection.visualDNA};
          const articlesDir=join(runtime.getDirectory(args.missionId),'media-assets');
          await mkdir(articlesDir,{recursive:true,mode:0o700});
          const report=await materializeEditionMedia({
            mediaPlan:compiled.mediaPlan,visualPlan,articles:compiled.articles,articlesDir,
            enterpriseId:job.enterpriseId,
            aiGenerationAuthorized:snapshot.mediaGenerationAuthorized===true&&job.input?.allowAiGeneration===true,
            apiKey:process.env.OPENAI_API_KEY||null,
            imageModel:process.env.BUYERSITE_IMAGE_MODEL||'gpt-image-2',
            maxAiImages:4,
          });
          await writeFile(join(runtime.getDirectory(args.missionId),'media-report.json'),JSON.stringify(report,null,2)+'\n',{mode:0o600});
          return {
            planSha256:compiled.mediaPlan.plan_sha256,
            reportSha256:jsonSha(report),
            images:report.images.map(image=>({
              pageId:image.page_id,kind:image.kind,sha256:image.sha256,credit:image.credit,
            })),
          };
        };
        void scheduleBackground(async()=>{
          try{await complete(seatId,args,await work());}
          catch(error){await runtime.failTask({...args,seatId,code:error.code||'MEDIA_MATERIALIZE_FAILED',message:safeError(error)}).catch(()=>{});}
        });
        return {status:'RUNNING',missionId:args.missionId,taskId:args.taskId,detail:'Media materialization is running in the private worker.'};
      }
      case 'buyersite_issue_compile':{
        requireSeatTask(seatId,args,'production-editor','compile-issue');
        const compiledArtifact=await runtime.getArtifact(args.missionId,'compile-enterprise',seatId,'compile-issue',args.taskAccessToken);
        const draft=await runtime.getArtifact(args.missionId,'draft-editorial-copy',seatId,'compile-issue',args.taskAccessToken);
        const mediaReport=JSON.parse(await readFile(join(runtime.getDirectory(args.missionId),'media-report.json'),'utf8'));
        const issue=compileMagazineIssueFromEnterprise({
          compiled:compiledArtifact.compiled,outline:compiledArtifact.outline,
          mediaPlan:compiledArtifact.compiled.mediaPlan,mediaReport,
        });
        const questionSpread=issue.spreads.find(item=>item.id==='buyer-questions');
        if(!questionSpread)fail('EDITORIAL_BUYER_QUESTIONS_SPREAD_MISSING',500);
        questionSpread.questions=draft.buyerQuestions.map(({title,body})=>({title,body}));
        questionSpread.evidenceRefs=[...new Set([...questionSpread.evidenceRefs,...draft.buyerQuestions.flatMap(item=>item.evidenceRefs)])];
        assertMagazineIssue(issue);
        const articlesDir=join(runtime.getDirectory(args.missionId),'media-assets');
        await assertIssueMediaFiles({issue,articlesDir});
        return complete(seatId,args,{
          issue,issueSha256:jsonSha(issue),spreadCount:issue.spreads.length,
          articleCount:compiledArtifact.compiled.articles.length,
        });
      }
      case 'buyersite_issue_build_preview':{
        requireSeatTask(seatId,args,'production-editor','build-private-preview');
        const work=async()=>{
          const job=runtime.getJob(args.missionId);
          const sourceBytes=await runtime.readSourceBytes(args.missionId);
          const captureArtifact=await runtime.getArtifact(args.missionId,'capture-source',seatId,'build-private-preview',args.taskAccessToken);
          const draft=await runtime.getArtifact(args.missionId,'draft-editorial-copy',seatId,'build-private-preview',args.taskAccessToken);
          const artDirection=await runtime.getArtifact(args.missionId,'art-direction',seatId,'build-private-preview',args.taskAccessToken);
          const result=await buildJob({
            job,sourceBytes,jobDir:runtime.getDirectory(args.missionId),projectRoot,
            websiteSnapshot:captureArtifact.snapshot,editorialDraft:draft,artDirection,
          });
          await writeFile(join(runtime.getDirectory(args.missionId),'build-internal.json'),JSON.stringify({
            artifactDir:result.artifactDir,sourceRoot:result.sourceRoot,
            artifactHash:result.artifactHash,revision:result.revision,
          },null,2)+'\n',{mode:0o600});
          return {
            artifactSha256:result.artifactHash,revision:result.revision,
            previewPath:'private-preview/'+result.revision,
            previewOnly:true,publication:'BLOCKED',
            visualReview:result.visualReview,
          };
        };
        void scheduleBackground(async()=>{
          try{await complete(seatId,args,await work());}
          catch(error){await runtime.failTask({...args,seatId,code:error.code||'PRIVATE_BUILD_FAILED',message:safeError(error)}).catch(()=>{});}
        });
        return {status:'BUILDING',missionId:args.missionId,taskId:args.taskId,detail:'The private Astro preview is building. Wait for the durable task state to change.'};
      }
      case 'buyersite_review_content':{
        requireSeatTask(seatId,args,'standards-editor','review-content');
        const internal=JSON.parse(await readFile(join(runtime.getDirectory(args.missionId),'build-internal.json'),'utf8'));
        const issue=JSON.parse(await readFile(join(internal.sourceRoot,'magazine-issue.json'),'utf8'));
        assertMagazineIssue(issue);
        const evidence=JSON.parse(await readFile(join(internal.sourceRoot,'evidence.json'),'utf8'));
        const known=new Set(evidence.map(item=>item.evidence_id));
        for(const spread of issue.spreads){
          if(spread.evidenceRefs.some(ref=>!known.has(ref)))fail('CONTENT_REVIEW_UNKNOWN_EVIDENCE',409);
        }
        return complete(seatId,args,{status:'PASS_RECOMMENDED',findings:[],issueSha256:jsonSha(issue),evidenceCount:evidence.length});
      }
      case 'buyersite_review_media':{
        requireSeatTask(seatId,args,'standards-editor','review-media');
        const work=async()=>{
          const internal=JSON.parse(await readFile(join(runtime.getDirectory(args.missionId),'build-internal.json'),'utf8'));
          const sourceRoot=internal.sourceRoot;
          const [pages,mediaReport]=await Promise.all(['pages.json','media-report.json'].map(file=>
            readFile(join(sourceRoot,file),'utf8').then(JSON.parse)));
          const reviews=[];
          const findings=[];
          for(const asset of mediaReport.images){
            const page=pages.find(item=>item.page_id===asset.page_id);
            if(!page)fail('MEDIA_REVIEW_PAGE_MISSING',409);
            const bytes=await readFile(join(sourceRoot,'articles','hero-'+asset.page_id+'.png'));
            const review=await reviewMediaAsset({
              page:{page_id:page.page_id,path:page.path,title:page.title},
              asset,bytes,apiKey:process.env.OPENAI_API_KEY||null,
            });
            reviews.push(review);
            for(const issue of review.assessment?.issues||[]){
              findings.push({severity:issue.severity,message:issue.problem});
            }
            if(asset.kind==='abstract-fallback')findings.push({
              severity:'major',message:'Abstract fallback artwork is preview-only and cannot pass publication media review',
            });
          }
          const passed=reviews.length===mediaReport.images.length&&reviews.every(item=>item.decision==='pass')&&
            !mediaReport.images.some(item=>item.kind==='abstract-fallback');
          return {
            status:passed?'PASS_RECOMMENDED':'REVISION_REQUIRED',
            findings:findings.slice(0,80),receipts:reviews.map(item=>({
              pageId:item.page_id,decision:item.decision,bindingSha256:item.binding_sha256,imageSha256:item.image_sha256,
            })),
          };
        };
        void scheduleBackground(async()=>{
          try{await complete(seatId,args,await work());}
          catch(error){await runtime.failTask({...args,seatId,code:error.code||'MEDIA_REVIEW_FAILED',message:safeError(error)}).catch(()=>{});}
        });
        return {status:'REVIEWING',missionId:args.missionId,taskId:args.taskId,detail:'Media review is running against the exact rendered image bytes.'};
      }
      case 'buyersite_review_visuals':{
        requireSeatTask(seatId,args,'standards-editor','review-visuals');
        const report=JSON.parse(await readFile(join(runtime.getDirectory(args.missionId),'visual-review.json'),'utf8'));
        const findings=(report.pages||[]).flatMap(page=>(page.assessment?.issues||[]).map(issue=>({
          severity:issue.severity,message:issue.problem,
        }))).slice(0,80);
        return complete(seatId,args,{
          status:report.status,findings,
          artifactSha256:report.artifact_sha256||null,
          coverage:report.coverage||null,
        });
      }
      case 'buyersite_verify_output':{
        requireSeatTask(seatId,args,'production-editor','verify-output');
        const dir=runtime.getDirectory(args.missionId);
        const [internal,manifestFile]=await Promise.all([
          readFile(join(dir,'build-internal.json'),'utf8').then(JSON.parse),
          readFile(join(dir,'artifact-manifest.json'),'utf8').then(JSON.parse),
        ]);
        if(manifestFile.artifactHash!==internal.artifactHash||manifestFile.previewOnly!==true||
           manifestFile.publication!=='BLOCKED'||!Array.isArray(manifestFile.files))fail('PRIVATE_OUTPUT_MANIFEST_INVALID',409);
        await stat(join(internal.artifactDir,'index.html'));
        return complete(seatId,args,{
          status:'PASS',artifactSha256:manifestFile.artifactHash,
          fileCount:manifestFile.files.length,previewOnly:true,publication:'BLOCKED',
        });
      }
      default:
        fail('MCP_TOOL_NOT_FOUND',404);
    }
  }

  async function handle(request,response,url){
    const match=url.pathname.match(/^\/mcp\/([a-z][a-z0-9-]{1,63})$/);
    if(!match)return false;
    const seatId=match[1];
    if(!manifest.seats.some(seat=>seat.id===seatId))fail('EDITORIAL_SEAT_UNKNOWN',404);
    if(request.method!=='POST'){
      response.setHeader('allow','POST');
      await writeResponse(response,405,{error:'MCP_METHOD_NOT_ALLOWED'});
      return true;
    }
    authorizedSeat(request,missionSecret,seatId);
    const message=await readRequestBody(request);
    if(!obj(message)||message.jsonrpc!=='2.0'||typeof message.method!=='string') {
      await writeResponse(response,400,jsonRpcError(message?.id??null,-32600,'Invalid JSON-RPC request'));
      return true;
    }
    const id=message.id??null;
    if(message.method==='notifications/initialized'||message.method.startsWith('notifications/')){
      await writeResponse(response,202,null);
      return true;
    }
    if(message.method==='initialize'){
      const requested=message.params?.protocolVersion;
      const supported=['2025-03-26','2024-11-05','2025-06-18','2025-11-25'];
      const protocolVersion=supported.includes(requested)?requested:'2025-03-26';
      await writeResponse(response,200,{
        jsonrpc:'2.0',id,
        result:{protocolVersion,capabilities:{tools:{listChanged:false}},
          serverInfo:{name:'buyersite-editorial-department',version:'0.1.0'}},
      });
      return true;
    }
    if(message.method==='ping'){
      await writeResponse(response,200,{jsonrpc:'2.0',id,result:{}});
      return true;
    }
    if(message.method==='tools/list'){
      await writeResponse(response,200,{jsonrpc:'2.0',id,result:{tools:toolList(seatId)}});
      return true;
    }
    if(message.method==='tools/call'){
      const params=message.params||{};
      if(typeof params.name!=='string'||!obj(params.arguments||{})){
        await writeResponse(response,200,jsonRpcError(id,-32602,'Invalid tool arguments'));
        return true;
      }
      const allowed=toolList(seatId).some(tool=>tool.name===params.name);
      if(!allowed){
        await writeResponse(response,200,toolFailure(id,Object.assign(new Error('MCP_TOOL_NOT_FOUND'),{code:'MCP_TOOL_NOT_FOUND'})));
        return true;
      }
      try{
        const result=await callTool(seatId,params.name,params.arguments||{});
        await writeResponse(response,200,toolResult(id,result));
      }catch(error){
        await writeResponse(response,200,toolFailure(id,error));
      }
      return true;
    }
    await writeResponse(response,200,jsonRpcError(id,-32601,'Method not found'));
    return true;
  }

  return Object.freeze({handle,async idle(){await background;}});
}

function requireSeatTask(actualSeat,args,expectedSeat,expectedTask){
  if(actualSeat!==expectedSeat)fail('MCP_SEAT_CAPABILITY_DENIED',403);
  if(!obj(args)||args.taskId!==expectedTask||
     typeof args.missionId!=='string'||typeof args.claimToken!=='string'||typeof args.taskAccessToken!=='string')fail('MCP_TASK_BINDING_INVALID',400);
}
